// Writes docs/ACCURACY_REPORT.md from the content JSON (fact → where → source → status).
// Usage: node tools/accuracy_report.mjs
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
const C = "apps/web/src/content";
const j = (p) => JSON.parse(readFileSync(`${C}/${p}`, "utf8"));
const sources = j("sources.json").sources;
const SRC = new Map(sources.map((s) => [s.id, s]));
const rows = [];
const add = (where, text, ids) => rows.push({ where, text, ids: ids ?? [] });
const home = existsSync(`${C}/homecoming.json`) ? j('homecoming.json') : { debrief: [], closing: [], travel: [], ending: [], endcard: [], checklist: [] };
for (const l of [...home.debrief,...home.closing,...home.travel,...home.ending,...home.endcard,...home.checklist.map(c=>c.fact)]) if(l.type==='fact') add(`Homecoming / ${l.id}`,l.text,l.sourceIds);
for (const [tag, file] of [["Ch1 Moon", "chapters/ch1-moon.json"], ["Ch2 Mars", "chapters/ch2-mars.json"]]) {
  const ch = j(file);
  for (const b of ch.beats) {
    for (const l of b.lines) if (l.type === "fact") add(`${tag} · ${b.id}`, l.text, l.sourceIds);
    if (b.card?.type === "fact") add(`${tag} · ${b.id} card`, b.card.text, b.card.sourceIds);
    if (b.plaque) add(`${tag} · plaque`, b.plaque.lines.join(" / "), b.plaque.sourceIds);
  }
  if (ch.secret) add(`${tag} · secret`, ch.secret.text, ch.secret.sourceIds);
}
for (const [tag, file] of [["Quiz Ch1", "questions/ch1-moon.json"], ["Quiz Ch2", "questions/ch2-mars.json"]])
  for (const q of j(file).questions) add(`${tag} · ${q.id}`, `${q.prompt} → ${q.options.filter((o) => o.correct || o.order !== undefined).map((o) => o.label).join(" / ")}`, q.sourceIds);
for (const t of j("teasers.json").teasers) for (const l of t.lines) if (l.type === "fact") add(`Teaser · ${t.chapter}`, l.text, l.sourceIds);
for (const c of j("curiosities.json").curiosities) add(`Curiosity · ${c.world}`, c.text, c.sourceIds);
for (const [k, g] of Object.entries(j("glossary.json").terms)) if (g.sourceIds) add(`Glossary · ${k}`, g.kid, g.sourceIds);

if (existsSync(`${C}/missions`)) {
  const walk = (v, path) => {
    if (!v || typeof v !== "object") return;
    if (v.kind === "fact") add(path, v.text, [v.sourceId]);
    for (const [k, x] of Object.entries(v)) walk(x, `${path}/${k}`);
  };
  for (const f of readdirSync(`${C}/missions`).filter((f) => f.endsWith(".json"))) walk(j(`missions/${f}`), `Mission ${f}`);
}
const bad = rows.filter((r) => !r.ids.length || r.ids.some((id) => SRC.get(id)?.status !== "verified"));
const md = [
  "# Accuracy report",
  "",
  `Generated by \`node tools/accuracy_report.mjs\` on ${new Date().toISOString().slice(0, 10)}. Every TRUE STORY line, quiz answer, teaser fact, secret, curiosity and glossary definition, with its source and status.`,
  "",
  `**${rows.length} facts · ${sources.length} sources · ${bad.length} problems.** Make-believe lines (IMAGINE) are not listed. The "Never say" list lives in \`apps/web/src/content/glossary.json\` and bible §16.`,
  "",
  "## Facts",
  "",
  "| Where | Fact | Source(s) | Status |",
  "|---|---|---|---|",
  ...rows.map((r) => `| ${r.where} | ${r.text.replace(/\|/g, "/")} | ${r.ids.join(", ")} | ${r.ids.map((id) => SRC.get(id)?.status ?? "missing").join(", ")} |`),
  "",
  "## Sources",
  "",
  "| Id | Publisher | Title | Status | Note |",
  "|---|---|---|---|---|",
  ...sources.map((s) => `| ${s.id} | ${s.publisher} | [${s.title.replace(/\|/g, "/")}](${s.url}) | ${s.status} | ${(s.note ?? "").replace(/\|/g, "/")} |`),
  "",
  "## Kept out on purpose",
  "",
  "- The ~220-yard roll distance of Opportunity's landing (F17 note): not confirmed by a NASA page, so unused.",
  "- Any claim that the Eagle descent-stage foil is real gold: never stated.",
  "- \"My battery is low and it's getting dark\": a journalist's summary, not a rover message. Never used.",
  "- Opportunity's driving record: the game says Perseverance passed it on 11 Oct 2026 (F18).",
  "",
];
writeFileSync("docs/ACCURACY_REPORT.md", md.join("\n"));
console.log(`facts ${rows.length}, sources ${sources.length}, problems ${bad.length}`);
process.exitCode = bad.length ? 1 : 0;
