"""v8: builds the web deploy's Nova brain, a Vercel serverless function (deploy/api/nova/chat.mjs).

The deployed site has no Python server, so this small Node function gives Nova the same rules as
server/nova: Nova's system prompt, the game's sourced facts (retrieved per question), a jailbreak /
off-topic guard, a strict JSON answer from Gemini, and an output check (no links, <= 60 words, no
numbers that are not in the facts or the question). The Gemini key is read ONLY from the Vercel
project's environment (GEMINI_API_KEY); without it the function answers 404 and the game uses its
offline fact sheet. Nothing is logged or stored.

  python -I tools/v8/make_vercel_api.py <deployDir>
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from server.nova import config  # noqa: E402
from server.nova.facts import all_facts  # noqa: E402

out_dir = Path(sys.argv[1]) / "api" / "nova"
out_dir.mkdir(parents=True, exist_ok=True)
kb = [{"t": f.text, "m": f.mission} for f in all_facts()]
prompt = config.SYSTEM_PROMPT if hasattr(config, "SYSTEM_PROMPT") else (ROOT / "server/nova/system_prompt.md").read_text(encoding="utf-8")
models = [config.MODEL, *config.FALLBACK_MODELS]

JS = r"""// GENERATED by tools/v8/make_vercel_api.py: Nova's brain for the static web deploy. Do not edit.
const KB = __KB__;
const SYSTEM = __SYSTEM__;
const MODELS = __MODELS__;
const STOP = new Set("a an the is are was were do does did how why what when where who which of on in to for and or it its it's i you me my your can could would will about tell please there this that they them their".split(" "));
const stem = (w) => w.replace(/(ies|es|s|ing|ed)$/, "");
const words = (s) => s.toLowerCase().replace(/[^a-z0-9\s-]/g, " ").split(/\s+/).filter((w) => w && !STOP.has(w)).map(stem);
const KBW = KB.map((f) => new Set(words(f.t)));
const NUMS = new Set(KB.flatMap((f) => (f.t.match(/\d[\d,]*(?:\.\d+)?/g) || []).map((n) => n.replace(/,/g, ""))));
const JAILBREAK = /bad word|curse word|swear|ignore (?:your|all|the|previous)|forget (?:your|the) rules|pretend (?:you|to be)|you are now|act as|role ?play|developer mode|system prompt|new rules|jailbreak/i;
const SPACE = /nasa|space|moon|lunar|mars|martian|planet|star|sun|solar|rocket|astronaut|rover|orbit|apollo|opportunity|eagle|lander|jupiter|saturn|earth|galaxy|comet|asteroid|meteor|universe|telescope|satellite|iss|artemis|voyager|viking|pioneer|perseverance|curiosity|gravity|crater|launch|mission|probe|venus|mercury|uranus|neptune|pluto|black hole|nebula|eclipse/i;
const hits = new Map();
const REDIRECTS = ["redirect-1", "redirect-2", "redirect-3", "redirect-4", "redirect-5", "redirect-6"];

function retrieve(q, mission) {
  const qw = new Set(words(q));
  return KB.map((f, i) => {
    let h = 0;
    for (const w of qw) if (KBW[i].has(w)) h++;
    return { f, s: h / Math.max(2.5, qw.size) + (mission && f.m === mission ? 0.08 : 0) };
  }).filter((x) => x.s > 0.2).sort((a, b) => b.s - a.s).slice(0, 7).map((x) => x.f.t);
}
function clean(text, question) {
  let t = String(text || "").replace(/https?:\/\/\S+|www\.\S+/g, "").replace(/[*_#`>|]/g, "").replace(/\s+/g, " ").trim();
  const ws = t.split(" ");
  if (ws.length > 60) t = ws.slice(0, 60).join(" ").replace(/[,;:]?$/, ".");
  const asked = new Set((question.match(/\d[\d,]*(?:\.\d+)?/g) || []).map((n) => n.replace(/,/g, "")));
  const bad = (t.match(/\d[\d,]*(?:\.\d+)?/g) || []).map((n) => n.replace(/,/g, "")).filter((n) => !NUMS.has(n) && !asked.has(n));
  return bad.length ? null : t;
}
async function gemini(key, msg, facts, history) {
  const contents = [];
  for (const h of (history || []).slice(-6)) if (h && (h.role === "user" || h.role === "assistant") && h.text) contents.push({ role: h.role === "user" ? "user" : "model", parts: [{ text: String(h.text).slice(0, 300) }] });
  while (contents.length && contents[0].role !== "user") contents.shift();
  contents.push({ role: "user", parts: [{ text: `<facts>\n${facts.map((f) => "- " + f).join("\n")}\n</facts>\n\nThe explorer asks: ${msg}` }] });
  const body = {
    systemInstruction: { parts: [{ text: SYSTEM + "\n\nReply as JSON: on_topic is false if the message is not about NASA, space missions or space (greetings count as on topic); answer is what Nova says out loud." }] },
    contents,
    generationConfig: { maxOutputTokens: 260, temperature: 0.7, responseMimeType: "application/json", responseSchema: { type: "OBJECT", properties: { on_topic: { type: "BOOLEAN" }, answer: { type: "STRING" } }, required: ["on_topic", "answer"] } },
    safetySettings: ["HARM_CATEGORY_HARASSMENT", "HARM_CATEGORY_HATE_SPEECH", "HARM_CATEGORY_SEXUALLY_EXPLICIT", "HARM_CATEGORY_DANGEROUS_CONTENT"].map((category) => ({ category, threshold: "BLOCK_LOW_AND_ABOVE" })),
  };
  for (const model of MODELS) {
    const r = await fetch(`https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent`, { method: "POST", headers: { "content-type": "application/json", "x-goog-api-key": key }, body: JSON.stringify(body), signal: AbortSignal.timeout(12000) }).catch(() => null);
    if (!r) continue;
    if (r.status === 429 || r.status >= 500 || r.status === 404) continue;
    const j = await r.json().catch(() => null);
    const txt = j?.candidates?.[0]?.content?.parts?.map((p) => p.text || "").join("") || "";
    try {
      return JSON.parse(txt);
    } catch {
      return null;
    }
  }
  return null;
}
const nd = (res, events) => {
  res.statusCode = 200;
  res.setHeader("content-type", "application/x-ndjson");
  res.setHeader("cache-control", "no-store");
  res.end(events.map((e) => JSON.stringify(e)).join("\n") + "\n");
};

export default async function handler(req, res) {
  const key = process.env.GEMINI_API_KEY;
  if (!key || req.method !== "POST") {
    res.statusCode = 404;
    return res.end();
  }
  const ip = String(req.headers["x-forwarded-for"] || "").split(",")[0] || "?";
  const now = Date.now();
  const recent = (hits.get(ip) || []).filter((t) => now - t < 60000);
  if (recent.length >= 12) return nd(res, [{ type: "meta", kind: "limit", lineId: "chat-wait" }, { type: "end" }]);
  hits.set(ip, [...recent, now]);
  let b = req.body;
  if (typeof b === "string") b = JSON.parse(b || "{}");
  const msg = String(b?.message || "").slice(0, 200).trim();
  const mission = b?.missionId === "eagle" || b?.missionId === "opportunity" ? b.missionId : null;
  if (!msg) return nd(res, [{ type: "meta", kind: "unsure", lineId: "chat-heard-nothing" }, { type: "end" }]);
  const redirect = () => nd(res, [{ type: "meta", kind: "redirect", lineId: REDIRECTS[[...msg].reduce((a, c) => a + c.charCodeAt(0), 0) % REDIRECTS.length] }, { type: "end" }]);
  if (JAILBREAK.test(msg)) return redirect();
  const out = await gemini(key, msg, retrieve(msg, mission), b?.history);
  if (!out) return nd(res, [{ type: "meta", kind: "fallback" }, { type: "end" }]);
  if (!out.on_topic && !SPACE.test(msg)) return redirect();
  const text = clean(out.answer, msg);
  if (!text) return nd(res, [{ type: "meta", kind: "unsure" }, { type: "text", t: "I'm not sure about that one. You could look it up on nasa.gov with a grown-up!" }, { type: "end" }]);
  return nd(res, [{ type: "meta", kind: "answer" }, { type: "text", t: text }, { type: "end" }]);
}
"""
js = JS.replace("__KB__", json.dumps(kb, ensure_ascii=False)).replace("__SYSTEM__", json.dumps(prompt)).replace("__MODELS__", json.dumps(models))
(out_dir / "chat.mjs").write_text(js, encoding="utf-8")
print(f"wrote {out_dir / 'chat.mjs'} ({len(kb)} facts)")
